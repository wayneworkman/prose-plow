#!/usr/bin/env python3
"""Writes the chat reference of a plain-text ChatML checkpoint: a session of requests with replies.

    gen_chat_ref.py --model-dir DIR --out FILE

The session is what an application sends over the life of one conversation, each request being
the whole conversation so far: a first question, a second turn appended to the reply, the same
request again (regenerate), the last question changed, the first question changed, and a
conversation with another beginning. Every reply is the reference's greedy continuation of the
rendered conversation, generated by recomputing the whole prefix for each token and ended by
the end marker in the decoded text, so a request's reply depends on nothing but its messages.

The port has to produce the same replies while keeping its memory across the requests, which
for Boris-2 means rewinding through checkpoints of its recurrent state; this file is what
that is checked against (native/tests/test_boris2_chat.cpp).

The output is a function of the checkpoint and of the PyTorch build: regenerate the committed
file only when the checkpoint changes, with the exact package versions of
native/requirements.txt.
"""
from __future__ import annotations

import argparse
import hashlib
import sys

from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import chatml_text  # noqa: E402
import formats  # noqa: E402
import reference_boris2  # noqa: E402

MAX_NEW_TOKENS = 64

SYSTEM = ("system", "Be brief.")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--model-dir", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()

    if not reference_boris2.is_boris2(args.model_dir):
        parser.error(f"{args.model_dir} is not a Boris-2 checkpoint")
    model, config = reference_boris2.load_reference(args.model_dir)
    tokenizer = chatml_text.ChatTokenizer(args.model_dir)
    eos = config.eos_token_id
    requests: list[formats.ChatRequest] = []

    def ask(messages: list[tuple[str, str]]) -> str:
        prompt = tokenizer.encode(tokenizer.render(messages, add_generation_prompt=True))
        reply, text = chatml_text.greedy_reply(model, tokenizer, prompt, eos, MAX_NEW_TOKENS)
        # One conversation is one document for the port: the end-of-text token is never fed.
        assert eos not in prompt + reply
        ended = text is not None and chatml_text.END_MARKER in tokenizer.decode(reply)
        if text is None:
            text = tokenizer.decode(reply)
        requests.append(formats.ChatRequest(list(messages), prompt, reply, ended, text))
        return text

    # A first question and its reply; outer whitespace in a message is trimmed by the template.
    first = [SYSTEM, ("user", "  What is 2 + 2?  ")]
    answer_1 = ask(first)
    # A second turn: the reply comes back as a message and a new question is appended.
    second = first + [("assistant", answer_1), ("user", "And 3 + 3?")]
    answer_2 = ask(second)
    # Regenerate: the very same request again.
    ask(second)
    # A third turn on top, so that the conversation has a history worth rewinding into.
    third = second + [("assistant", answer_2), ("user", "Write a haiku.\nAbout rain.")]
    ask(third)
    # The last question of the second turn changed: everything before it is kept.
    ask(first + [("assistant", answer_1), ("user", "And 5 + 5?")])
    # The first question changed: only the system message is kept.
    ask([SYSTEM, ("user", "What is the capital of France?")])
    # Another beginning: nothing is kept. Without the instruction to be brief the reply is cut
    # by the length limit, which is the other way a reply ends.
    ask([("user", "What is the water cycle?")])
    # And back to the first conversation, as it stood after two turns.
    ask(second)

    assert sum(r.ended for r in requests) >= 5 and not all(r.ended for r in requests), [r.ended for r in requests]
    sha = hashlib.sha256((args.model_dir / "tokenizer.json").read_bytes()).hexdigest()
    formats.write_chat_reference(args.out, sha, MAX_NEW_TOKENS, requests)
    print(f"gen_chat_ref: wrote {args.out}: {len(requests)} requests, {sum(len(r.reply) for r in requests)} reply tokens, "
          f"{sum(r.ended for r in requests)} replies ended by the marker, {args.out.stat().st_size} bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
